/**
 * Every interface string, with the English value of ICQ New 23.2.0 word for word
 * (docs/research/icq-new-ui-spec.json, `strings.<context>.<key>.en`).
 * Strings the original never had (sign-up without SMS, our About page) are
 * marked "openICQ" and kept in the same tone.
 */

/** Replaces %1, %2, ... with the given values. */
export function fmt(template: string, ...values: Array<string | number>): string {
  return template.replace(/%(\d)/g, (match, digit: string) => {
    const value = values[Number(digit) - 1];
    return value === undefined ? match : String(value);
  });
}

